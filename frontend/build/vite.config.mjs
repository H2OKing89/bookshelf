import path from 'node:path';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import babel from '@babel/core';
import react from '@vitejs/plugin-react';
import { defineConfig, normalizePath } from 'vite';
import { patchCssModules } from 'vite-css-modules';
import sourceProvenance from './SourceProvenancePlugin.js';
import postcssConfig from '../postcss.config.js';

const frontend = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repository = path.dirname(frontend);
const src = path.join(frontend, 'src');
const output = path.join(repository, '_output/UI');
const localization = path.join(repository, 'src/NzbDrone.Core/Localization/Core');
const srcPrefix = `${normalizePath(src)}/`;
const cleanFile = (id) => id.split('?')[0];

// Most existing source files contain JSX in .js files. Keep their existing
// Babel syntax transforms until they are migrated to TSX individually.
function legacyJavaScript(production) {
  return {
    name: 'bookshelf-legacy-jsx',
    enforce: 'pre',
    async transform(code, id) {
      if (!id.startsWith(srcPrefix) || !id.endsWith('.js')) {
        return;
      }

      // Styles/Variables are also read synchronously by PostCSS. Keep their
      // source as CJS and expose their literal default export to native ESM.
      const input = id.startsWith(`${srcPrefix}Styles/Variables/`) ? code.replace(/^module\.exports = /m, 'export default ') : code;
      const result = await babel.transformAsync(input, {
        filename: id,
        configFile: path.join(frontend, 'babel.config.js'),
        envName: production ? 'production' : 'development',
        babelrc: false,
        sourceMaps: true
      });
      return { code: result.code, map: result.map };
    }
  };
}

// The historical convention in this tree is .css for component modules. Vite
// recognizes .module.css; an import query keeps the canonical source file and
// HMR watch identity unchanged without renaming hundreds of existing modules.
function legacyCssModules() {
  return {
    name: 'bookshelf-css-module-imports',
    enforce: 'pre',
    async resolveId(source, importer, options) {
      if (!importer || !/\.[jt]sx?$/.test(cleanFile(importer)) || !source.endsWith('.css') || source.endsWith('.module.css')) {
        return;
      }

      const resolved = await this.resolve(source, importer, { ...options, skipSelf: true });
      if (!resolved?.id.startsWith(srcPrefix) || resolved.id.endsWith('/Styles/globals.css')) {
        return;
      }
      return { ...resolved, id: `${resolved.id}?.module.css` };
    }
  };
}

function cssModuleTypes(file, exports, verify) {
  const source = cleanFile(file);
  if (!normalizePath(source).startsWith(srcPrefix)) {
    return;
  }

  const declaration = `${source}.d.ts`;
  const classes = Object.keys(exports).sort().map((name) => `  '${name}': string;`).join('\n');
  const expected = `// This file is automatically generated.\n// Please do not change this file!\ninterface CssExports {\n${classes}\n}\nexport const cssExports: CssExports;\nexport default cssExports;\n`;
  if (existsSync(declaration) && readFileSync(declaration, 'utf8') === expected) {
    return;
  }
  if (verify) {
    throw new Error(`Outdated CSS declarations: ${path.relative(repository, declaration)}. Run yarn build to regenerate.`);
  }
  writeFileSync(declaration, expected);
}

function staticContent(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const file = path.join(directory, entry.name);
    return entry.isDirectory() ? staticContent(file) : [file];
  });
}

function staticFiles() {
  const files = () => [...staticContent(path.join(src, 'Content')), path.join(src, 'oauth.html')];
  return {
    name: 'bookshelf-static-content',
    apply: 'build',
    buildStart() {
      files().forEach((file) => this.addWatchFile(file));
    },
    generateBundle() {
      for (const file of files()) {
        this.emitFile({ type: 'asset', fileName: normalizePath(path.relative(src, file)), source: readFileSync(file) });
      }
    }
  };
}

function developmentHtml(urlBase) {
  return {
    name: 'bookshelf-dev-html',
    apply: 'serve',
    transformIndexHtml(html) {
      return html.replace(/((?:href|src)=")(?=\/(?:Content\/|favicon\.ico))/g, `$1${urlBase}`).replaceAll('__URL_BASE__', urlBase);
    },
    configureServer(server) {
      // Localization is still authenticated by the backend. The dev backend
      // may be configured to read these live source dictionaries directly.
      const variables = path.join(src, 'Styles/Variables');
      const mixins = path.join(src, 'Styles/Mixins');
      server.watcher.add([localization, variables, mixins]);
      server.watcher.on('change', (file) => {
        const directory = path.dirname(file);
        if (directory === variables || directory === mixins) {
          server.moduleGraph.invalidateAll();
          server.ws.send({ type: 'full-reload' });
        } else if (directory === localization && file.endsWith('.json')) {
          server.ws.send({ type: 'full-reload' });
        }
      });
    }
  };
}

function developmentSettings() {
  const backend = new URL(process.env.BOOKSHELF_DEV_BACKEND ?? 'http://127.0.0.1:8787');
  if (!['http:', 'https:'].includes(backend.protocol) || !['127.0.0.1', 'localhost', '[::1]'].includes(backend.hostname) || backend.username || backend.password || backend.search || backend.hash) {
    throw new Error('BOOKSHELF_DEV_BACKEND must point to a local HTTP(S) development backend.');
  }
  const urlBase = backend.pathname.replace(/\/$/, '');
  const routes = ['api', 'signalr', 'login', 'logout', 'initialize.json', 'oauth.html', 'favicon.ico', 'MediaCover', 'MediaCoverProxy', 'feed', 'logfile', 'updatelogfile', 'backup', 'Content/assets', 'Content/styles.css'];
  const escape = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const proxy = Object.fromEntries(routes.map((route) => [`^${escape(urlBase)}/${escape(route)}(?:/|\\?|$)`, {
    target: backend.origin,
    ws: route === 'signalr',
    autoRewrite: true
  }]));
  return { urlBase, proxy };
}

const aliases = readdirSync(src, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .flatMap(({ name }) => [
    { find: name, replacement: path.join(src, name) },
    { find: `~${name}`, replacement: path.join(src, name) }
  ]);

export default defineConfig(({ command, mode }) => {
  const production = command === 'build';
  const profiling = mode === 'profile';
  const { urlBase, proxy } = production ? { urlBase: '', proxy: {} } : developmentSettings();

  return {
    root: src,
    base: `${urlBase}/`,
    publicDir: false,
    cacheDir: path.join(repository, '_cache/vite'),
    plugins: [
      legacyCssModules(),
      patchCssModules({ exportMode: 'default' }),
      legacyJavaScript(production),
      react({ jsxRuntime: 'automatic' }),
      staticFiles(),
      developmentHtml(urlBase),
      sourceProvenance()
    ],
    define: { __DEV__: JSON.stringify(!production) },
    // The dependency crawler runs before source transforms. It must also
    // understand the historical .js JSX convention.
    optimizeDeps: { rolldownOptions: { moduleTypes: { '.js': 'jsx' } } },
    resolve: {
      alias: [
        ...aliases,
        { find: /^~(?=\.)/, replacement: '' },
        { find: /^jquery$/, replacement: 'jquery/dist/jquery.min.js' },
        { find: /^react-middle-truncate$/, replacement: 'react-middle-truncate/lib/react-middle-truncate' },
        // react-virtualized's ESM build contains an invalid Flow type import.
        { find: /^react-virtualized$/, replacement: 'react-virtualized/dist/commonjs/index.js' },
        ...(profiling ? [{ find: /^react-dom$/, replacement: 'react-dom/profiling' }] : [])
      ]
    },
    css: {
      postcss: postcssConfig,
      modules: {
        generateScopedName(name, filename) {
          const file = cleanFile(filename);
          const relative = normalizePath(path.isAbsolute(file) ? path.relative(src, file) : file);
          const hash = createHash('sha256').update(relative).update('\0').update(name).digest('hex').slice(0, 6);
          return `${path.basename(file).replace(/(?:\.module)?\.css$/, '')}-${name}-${hash}`;
        },
        getJSON: (file, exports) => cssModuleTypes(file, exports, mode === 'verify')
      }
    },
    build: {
      outDir: output,
      emptyOutDir: true,
      assetsDir: 'Content/assets',
      target: 'baseline-widely-available',
      sourcemap: true,
      minify: profiling ? false : undefined,
      rollupOptions: {
        input: {
          index: path.join(src, 'index.html'),
          login: path.join(src, 'login.html')
        }
      }
    },
    experimental: {
      // HTML is rewritten by the backend for its configured URL base. Chunks,
      // workers and CSS dependencies resolve relative to a built module's URL.
      renderBuiltUrl(filename, { hostType }) {
        return hostType === 'html' ? `/${filename}` : { relative: true };
      }
    },
    server: {
      host: '127.0.0.1',
      port: Number(process.env.BOOKSHELF_DEV_PORT ?? 8788),
      strictPort: true,
      proxy
    }
  };
});
